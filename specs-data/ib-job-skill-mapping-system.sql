CREATE TABLE category_master (
    category_id SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    category_name          VARCHAR(100) NOT NULL,
    created_at          TIMESTAMP DEFAULT now(),
    UNIQUE (category_name)
);

CREATE TABLE skill_master (
    skill_id            VARCHAR(50) PRIMARY KEY,
    skill_name          VARCHAR(100) NOT NULL,
    category_id SMALLINT NOT NULL,
    created_at          TIMESTAMP DEFAULT now(),
    UNIQUE (skill_name),
    CONSTRAINT fk_category
		FOREIGN KEY (category_id)
		REFERENCES category_master (category_id)
		ON DELETE CASCADE
);


CREATE TYPE work_type_enum AS ENUM (
    'wfo',
    'wfh',
    'hybrid'
);

CREATE TABLE team_member (
    team_member_id          VARCHAR(50) PRIMARY KEY,
    designation             VARCHAR(100),
    profile_type            VARCHAR(50),
	is_active      			BOOLEAN DEFAULT true,
    experience_in_months    INTEGER,
    base_location           VARCHAR(100),
    work_type work_type_enum,
    profile_url             VARCHAR(1024),
    created_at              TIMESTAMP DEFAULT now()
);

CREATE TABLE team_member_allocation (
    team_member_id          VARCHAR(50) REFERENCES team_member(team_member_id),
    project_id              VARCHAR(50),
    allocation_percentage   NUMERIC(5,2),
    start_date              DATE,
    end_date                DATE,
    billable                BOOLEAN,
    is_deleted              BOOLEAN DEFAULT false,
	
    PRIMARY KEY (team_member_id, project_id)
);
CREATE INDEX idx_allocation_member
ON team_member_allocation(team_member_id);

CREATE TABLE team_member_skill (
    team_member_id      VARCHAR(50) REFERENCES team_member(team_member_id),
    skill_id            VARCHAR(50) REFERENCES skill_master(skill_id),
    rating              INTEGER,
    experience_in_months    INTEGER,
    is_deleted          BOOLEAN DEFAULT false,
	PRIMARY KEY (team_member_id, skill_id)
);

CREATE INDEX idx_team_member_skill_skill
ON team_member_skill(skill_id);

CREATE TABLE team_member_skill_certification (
    id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    certification_id    VARCHAR(100),
    team_member_id      VARCHAR(50)  NOT NULL,
    skill_id            VARCHAR(50)  NOT NULL,
    certificate   		VARCHAR(150),
    issuer              VARCHAR(100),
    issued_date         DATE,
    valid_till          DATE,
    FOREIGN KEY (team_member_id, skill_id)
        REFERENCES team_member_skill(team_member_id, skill_id)
);

-- =========================================================
-- TABLE: langgraph_checkpoints
-- =========================================================
CREATE TABLE langgraph_checkpoints (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL,
    node_name VARCHAR(50) NOT NULL,
    state_json JSONB NOT NULL,
	token_count INT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_lg_checkpoint_request
        FOREIGN KEY (request_id)
        REFERENCES requisition_requests (request_id)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX idx_req_node ON langgraph_checkpoints(request_id, node_name);
CREATE INDEX idx_lg_created_at ON langgraph_checkpoints(created_at);

