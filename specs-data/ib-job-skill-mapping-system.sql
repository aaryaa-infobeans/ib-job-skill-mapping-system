-- =========================================================
-- TABLE: requisition_requests
-- =========================================================
CREATE TABLE requisition_requests (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL UNIQUE,
    auth_client_id SMALLINT NOT NULL,
    status SMALLINT NOT NULL,
    client_name VARCHAR(100) NOT NULL,
    correlation_id VARCHAR(100),
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,

    CONSTRAINT fk_req_auth_client
        FOREIGN KEY (auth_client_id)
        REFERENCES auth_clients (id),

    CONSTRAINT fk_req_status
        FOREIGN KEY (status)
        REFERENCES requisition_status_master (status_id)
);

