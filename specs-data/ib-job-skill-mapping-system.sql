-- =========================================================
-- TABLE: auth_access_tokens
-- =========================================================
CREATE TABLE auth_access_tokens (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_client_id SMALLINT NOT NULL,
    access_token VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    is_revoked BOOLEAN NOT NULL DEFAULT FALSE,
    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_token_client
        FOREIGN KEY (auth_client_id)
        REFERENCES auth_clients (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_token_client ON auth_access_tokens(auth_client_id);
CREATE INDEX idx_token_expiry ON auth_access_tokens(expires_at);


